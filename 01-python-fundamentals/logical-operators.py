# logical operators
## and = checks two or more conditions if true
## or = checks if at least one condition is true
## not = True if condition is False, and vice versa

temp = 25
sunny = False

if temp > 0 and temp < 30:
    print('The tempreture is good')
else:
    print('The tempreture is good')


if temp > 0 or temp < 30:
    print('The tempreture is good')
else:
    print('The tempreture is good')

if not sunny:
    print('The tempreture is good')
else:
    print('The tempreture is good')
