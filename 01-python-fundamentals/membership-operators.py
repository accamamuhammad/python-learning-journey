# Membership Operators = used to test wheater a value or variable is found in a sequence (string, list, set or dictionary)

name = [1, 2, 4, 5]

if 2 in name:
    print('yes')
else:
    print('no')
    
capitals = {'Nigeria': 'Lagos',
            'Kenya': 'Nairobi',
            'Japan': 'Tokyo',
            'Uk': 'london'}

if 'Nigeria' in capitals:
    print('yes')
else:
    print('no')
